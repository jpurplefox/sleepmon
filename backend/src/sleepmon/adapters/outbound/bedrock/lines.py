"""Evolution lines keyed by the name on the game's candy label, with their sheets.

Generated by backend/scripts/evolution_lines.py from nitoyon/pokesleep-tool's data and
Pokémon Sleep's own sprites.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from difflib import get_close_matches
from functools import cache
from importlib.resources import files


@dataclass(frozen=True, slots=True)
class EvolutionLine:
    candy: str
    members: tuple[str, ...]
    sheet_webp: bytes = field(repr=False)


@cache
def _lines() -> dict[str, tuple[str, ...]]:
    raw = json.loads(files(__package__).joinpath("evolution_lines.json").read_text("utf-8"))
    return {candy: tuple(members) for candy, members in raw.items()}


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def find_line(name: str | None) -> EvolutionLine | None:
    """The line whose candy is ``name``, or that has ``name`` among its members.

    ``name`` may be the whole label ("Dwebble Candies", "Caramelos Magnemite"): when it
    matches no line as a whole, each of its words is tried.
    """
    if not name:
        return None
    for candidate in (name, *name.split()):
        line = _find(candidate)
        if line is not None:
            return line
    return None


def _find(name: str) -> EvolutionLine | None:
    wanted = name.strip().casefold()
    lines = _lines()
    candy = next((c for c in lines if c.casefold() == wanted), None)
    if candy is None:
        candy = next(
            (c for c, members in lines.items() if any(m.casefold() == wanted for m in members)),
            None,
        )
    if candy is None:
        # A misread name ("Dweeble") still finds the line of the closest known name.
        names = {c.casefold(): c for c in lines} | {
            m.casefold(): c for c, members in lines.items() for m in members
        }
        close = get_close_matches(wanted, names, n=1, cutoff=0.85)
        candy = names[close[0]] if close else None
    if candy is None:
        return None
    sheet = files(__package__).joinpath("lines", f"{_slug(candy)}.webp").read_bytes()
    return EvolutionLine(candy=candy, members=lines[candy], sheet_webp=sheet)
